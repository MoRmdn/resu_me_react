export function getCaseStudy(slug: string, locale: Locale): CaseStudy {
  const study = caseStudies.find((c) => c.slug === slug);
  if (!study) throw new Error(`No case study at /projects/${slug}/`);
  if (locale === "en") return study;
  const text = ar[slug];
  if (!text) throw new Error(`Missing Arabic case study: ${slug}`);
  return { ...study, ...text };
}
