export function localizeProject(project: Project, locale: Locale): Project {
  if (locale === "en") return project;
  const translation = ar[project.slug];
  if (!translation) throw new Error(`Missing Arabic project: ${project.slug}`);
  const alt = (text: string) => `${project.title} — ${text}`;
  return {
    ...project,
    ...translation,
    analyticsLabels: { category: project.category, country: project.country },
    // Technical detail is covered by the translated story/description.
    highlights: undefined,
    ledger: project.ledger?.map((item, i) => ({
      ...item,
      value: ["دون اتصال", "RTL", "100"][i],
      label: ["زيارات دون إنترنت", "تقارير عربية موقعة", "جهاز لكل دفعة"][i],
    })),
    media: project.media && {
      ...project.media,
      asset: project.media.asset && { ...project.media.asset, alt: alt("واجهة التطبيق") },
      screens: project.media.screens?.map((screen, i) => ({
        ...screen,
        alt: alt(`شاشة من التطبيق ${i + 1}`),
      })),
      social: project.media.social?.map((post, i) => ({
        ...post,
        alt: alt(`تصميم ترويجي ${i + 1}`),
      })),
    },
  };
}
export function getProjects(locale: Locale) {
  return {
    orderedProjects: orderedProjects.map((p) => localizeProject(p, locale)),
    featuredProjects: featuredProjects.map((p) => localizeProject(p, locale)),
    galleryProjects: galleryProjects.map((p) => localizeProject(p, locale)),
  };
}
