// Type-only and relative, so `npm run brief` (plain tsc, no path aliases) still
// compiles content/. Ties every service id to the analytics catalog: a service
// that is not declared there does not compile.
import type { EventParams } from "../lib/analytics/catalog";

/**
 * Content model for the portfolio.
 *
 * Every word and number the site renders lives under content/ — never inline in
 * a component. Ported from lib/data/portfolio_data.dart and
 * lib/utils/constants.dart of the Flutter original, reconciled against
 * Mohamed_Ramadan_CV_EN.pdf.
 */

export type ProjectAvailability =
  | "store_links"
  | "web"
  | "private"
  | "sign_in"
  | "discontinued"
  | "unavailable";

export type ProjectStory = {
  problem: string;
  responsibility: string;
  decisions: string[];
  result: string;
};

export type Project = {
  availability: ProjectAvailability;
  analyticsLabels?: { category: string; country: string };
  story?: ProjectStory;
  slug: string;
  title: string;
  /** One-line summary used on cards. */
  description: string;
  /** Full paragraph used on a featured panel and in a gallery plane. */
  longDescription: string;
  technologies: string[];
  tags: string[];
  /** Display country, uppercased by the UI. */
  country: string;
  category: string;
  /** The outcome line — a number wherever one is defensible. */
  achievement: string;
  links: { appStore?: string; playStore?: string; github?: string; website?: string };
  /**
   * Android application id. Rendered as visible text, not only in structured
   * data: a literal identifier search is matched against the served HTML.
   * Early apps carry client-chosen namespaces; see `publisherNamespace`.
   */
  bundleId?: string;
  /** Slug under public/images/ with generated AVIF/WebP variants, if any. */
  image?: { slug: string; width: number; height: number; alt: string };
  /** Supplied brand assets and how they are plated. See ProjectMedia. */
  media?: ProjectMedia;
  /**
   * Replaces the store links on a private card, so absence of links reads as
   * depth rather than a gap. DESIGN-SYSTEM §5.1.
   */
  ledger?: { value: string; label: string }[];
  /** Shown where store links would be, when there are none. */
  linkStatus?: string;
  /** Private client delivery: no public listing, gets its own card treatment. */
  isPrivate?: boolean;
  /** Extra detail bullets, shown only where the layout has room. */
  highlights?: string[];
  /**
   * Keep the name out of the meta keywords and the description's app list.
   * The project still renders and stays in the structured data.
   */
  hideFromKeywords?: boolean;
};

export type Experience = {
  slug: string;
  company: string;
  position: string;
  location: string;
  country: string;
  /** Free-form display strings, e.g. "January 2025". */
  startDate: string;
  endDate: string;
  /** ISO YYYY-MM, for sorting and <time> elements. */
  start: string;
  end: string | null;
  isCurrent: boolean;
  engagement?: string;
  description: string;
  achievements: string[];
  technologies: string[];
};

export type SkillGroup = {
  label: string;
  items: string[];
  /** At most one group may be highlighted — one copper accent per viewport. */
  highlighted?: boolean;
};

/**
 * How a project's supplied imagery is presented.
 *
 * DESIGN-SYSTEM §5.2 defines four plates, and one rule above all of them: no
 * supplied asset ever touches the page background directly. Containment only —
 * no blend modes, no background removal. Every `file` names a slug under
 * public/images/projects/, generated by `npm run images`.
 */
export type ProjectMedia = {
  /** Store icon, rendered inset in the 96px tile. */
  icon?: {
    file: string;
    /** Transparent sources get padding and no radius — there is no field to chip. */
    transparent?: boolean;
  };
  /**
   * - `device` — a capture seated whole on ink, bezel drawn by the frame.
   * - `field`  — an asset with its own brand ground, full-bleed via `cover`.
   * - `promo`  — a store promo shown whole via `contain`, never cropped.
   * - `icon`   — no capture; the icon tile carries the card.
   */
  plate: "device" | "field" | "promo" | "icon";
  asset?: {
    file: string;
    width: number;
    height: number;
    alt: string;
    /**
     * False when the source already includes its own device frame — drawing a
     * second bezel around a bezel looks like a mistake.
     */
    bezel?: boolean;
  };
  /**
   * Store-listing screens from one listing, shown whole as a set on a featured
   * panel. Featured panels use these in place of `asset`, which stays so the
   * project can move to the gallery by editing one list.
   */
  screens?: { file: string; width: number; height: number; alt: string }[];
  /** 1:1 posts. A different aspect, so they get their own strip. */
  social?: { file: string; width: number; height: number; alt: string }[];
};

/** A service's analytics id. Declared in lib/analytics/catalog.ts. */
export type ServiceId = EventParams<"service_page_click">["service_id"];

export type ServiceGroup = "apps" | "web" | "app_types";

/**
 * Evidence for a claim: a project on this site, a role, or this site itself.
 * `target` is a project slug, a case study slug, or `experience`. The page
 * resolves it: a case study when there is one, otherwise the homepage anchor.
 * `note` says what in that work backs this service.
 */
export type ServiceProof = { name: string; target: string; note: string };

/**
 * One service, and its page at /services/<slug>/.
 *
 * Every claim restates the marketplace bio (docs/marketplaces/bio-ar.md) or a
 * fact elsewhere in content/. No prices, timelines or response times until
 * Mohamed states them.
 */
export type Service = {
  id: ServiceId;
  slug: string;
  group: ServiceGroup;
  /** The card title, as on the homepage. */
  title: string;
  /** The page's H1 and <title>: the phrase people search for, once. */
  headline: string;
  /** Meta description, and the line under the title in lists. Under ~155 characters. */
  summary: string;
  /** Who it is for, in one line. */
  audience: string;
  /** What it is, in one sentence. */
  body: string;
  /** Three short lines for the homepage card. */
  includes: string[];
  /** "This is for you if…": the situations a client recognises themselves in. */
  situations: { title: string; body: string }[];
  /** The full scope, grouped. */
  scope: { title: string; items: string[] }[];
  /** What the client has at the end. */
  deliverables: string[];
  proof: ServiceProof[];
  /** Reviews whose `project` field matches one of these, shown on the page. */
  reviewProjects?: string[];
  /** Of those, the ones shown first, in this order. The rest sit behind a disclosure. */
  leadReviewIds?: string[];
  /** Questions, each with a stable id that never changes with the wording. */
  faq: { id: string; q: string; a: string }[];
  /** What I deliberately do not promise. */
  boundaries?: string[];
  related: ServiceId[];
  /** Prefills the WhatsApp chat. Never sent to analytics. */
  message: string;
};

/**
 * The full story of one project, at /projects/<slug>/. Structure after the
 * case studies of Very Good Ventures and LeanCode: what was asked, what was
 * decided and why, what changed, and what a client with a similar project
 * should know. Facts only from content/, the CV and the verbatim reviews.
 */
export type CaseStudy = {
  /** A project slug from projects.ts. */
  slug: string;
  /** The H1: the outcome, not the app name. */
  headline: string;
  /** Meta description and the lede under the H1. Under ~155 characters. */
  summary: string;
  /** The credits block. A missing period is omitted, never guessed. */
  facts: { client: string; role: string; period?: string; platforms: string };
  /** The client and the product. */
  context: string[];
  /** What was asked, and what made it hard. */
  challenge: string[];
  /** One bold line each, then why. */
  decisions: { title: string; body: string }[];
  /** What changed. A value only where the number is already defensible. */
  outcomes: { value?: string; label: string }[];
  /** Technical detail, for the developer reading over the client's shoulder. */
  highlights?: string[];
  /** For a reader whose project looks like this one. */
  lessons: string[];
  /** Services this project demonstrates, linked at the end. */
  services: ServiceId[];
  /** Verbatim reviews of this project, by id. */
  reviewIds?: string[];
  /** Other case studies to read next, by slug. */
  related: string[];
  /** Prefills the WhatsApp chat. Never sent to analytics. */
  message: string;
};
